// Standard concepts for the primary statements and how a printed row label maps to one. Pure: no I/O.
//
// Rules, all general (how annual and quarterly reports label these lines), none tuned to a company or a question:
//  - a label is compared after lower-casing and dropping punctuation, so "Total stockholders' equity" and
//    "Total Stockholders Equity:" are the same label;
//  - each concept lists label patterns in tiers; the best tier that has a row wins, and two different rows in the best tier
//    are AMBIGUOUS (never a guess);
//  - only rows of the concept's statement are looked at;
//  - a concept a company does not print (a bank has no gross profit) is not found; nothing is computed here.
// The synonym lists come from how the lines are named in the standard statements, not from any test question.
import type { Row, StatementId, StatementPage } from "./statements.ts";

export interface ConceptDef {
  id: string;
  statement: StatementId;
  /** Shown to the model and in results. */
  title: string;
  /** Tiers of label patterns, best first. A row matches a tier if any pattern matches its normalized label. */
  tiers: RegExp[][];
  /** A row whose nearest label-only line above must match (the "Diluted" row under "Earnings per share"). */
  context?: RegExp;
}

/** Lower case, apostrophes and punctuation dropped, spaces collapsed. */
export const normLabel = (label: string): string =>
  label
    .toLowerCase()
    .replace(/[’'`]/g, "")
    .replace(/\(.*?\)/g, " ") // "(loss)", "(note 5)"
    .replace(/[^a-z0-9 ]/g, " ")
    .replace(/\b(?:note|notes)\s+\d+\b/g, " ")
    .replace(/\s+/g, " ")
    .trim();

