export const CONCEPT_IDS = CONCEPTS.map((c) => c.id);
export const conceptById = (id: string): ConceptDef | undefined => CONCEPTS.find((c) => c.id === id.trim().toLowerCase().replace(/[\s-]+/g, "_"));

export interface Candidate {
  page: StatementPage;
  row: Row;
  tier: number;
}

/** Rows of the concept's statement whose labels fit its best tier, over all pages of that statement. */
export function candidatesFor(def: ConceptDef, pages: readonly StatementPage[]): { found: Candidate[]; misaligned: number } {
  let misaligned = 0;
  const hits: Candidate[] = [];
  for (const page of pages) {
    if (page.id !== def.statement) continue;
    for (const row of page.rows) {
      const label = normLabel(row.label);
      const tier = def.tiers.findIndex((t) => t.some((re) => re.test(label)));
      if (tier < 0) continue;
      if (def.context && !(row.context && def.context.test(row.context)) && !/per (?:common )?share|eps/.test(label)) continue;
      if (!row.aligned) {
        misaligned++;
        continue;
      }
      hits.push({ page, row, tier });
    }
  }
  if (hits.length === 0) return { found: [], misaligned };
  const best = Math.min(...hits.map((h) => h.tier));
  return { found: hits.filter((h) => h.tier === best), misaligned };
}
